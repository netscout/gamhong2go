// CharGenROM returns the pixel row for a given character and scanline.
// screenByte is the raw value from Apple II screen memory ($0400–$07FF).
// row is 0–7 (scanline within the character cell).
// Returns 7 pixel bits and whether the character should be inverted.
func CharGenROM(screenByte uint8, row int) (pixels uint8, inverse bool) {
	// Decode Apple II character encoding:
	//   $00–$3F → inverse display of character 0x40+code
	//   $40–$7F → flashing display of character code (we show normal)
	//   $80–$FF → normal display of character code & 0x7F
	var charIndex uint8
	switch {
	case screenByte < 0x40:
		charIndex = screenByte + 0x40
		inverse = true
	case screenByte < 0x80:
		charIndex = screenByte
		inverse = false // flashing: alternate with inverse at ~1.875 Hz
	default:
		charIndex = screenByte & 0x7F
		inverse = false
	}

	if row < 0 || row > 7 {
		return 0, inverse
	}

	pixels = charGen[int(charIndex)*8+row]
	return pixels, inverse
}
